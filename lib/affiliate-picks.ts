/** slot + 연령대에 맞는 추천 픽 목록 (없으면 default, 그것도 없으면 빈 배열) */
export function getAffiliatePicks(slot: SlotType, ageGroup: AgeGroup): AffiliatePick[] {
  const table = AFFILIATE_PICKS[slot]
  if (!table) return []
  return table[ageGroup] ?? table.default
}
